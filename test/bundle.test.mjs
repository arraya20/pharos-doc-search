// The CLI, the API and the dashboard must run the same code and the same data.
// These tests fail if any of the three drifts.
import test from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (...parts) => readFileSync(join(ROOT, ...parts), "utf8");

const srcEngine = read("src", "kb.mjs");
const browserEngine = read("public", "kb.mjs");

test("public/kb.mjs is a faithful copy of src/kb.mjs", () => {
  const normalise = (code) =>
    code
      .replace(/^\/\/ Copy of src\/kb\.mjs generated by scripts\/build-index\.mjs — do not edit\.\n/, "")
      .replace('from "./index.generated.js"', 'from "./index.generated.mjs"');
  assert.equal(normalise(browserEngine), normalise(srcEngine), "the browser engine drifted from the CLI engine");
});

test("the browser engine imports the browser index, not the node one", () => {
  assert.match(browserEngine, /from "\.\/index\.generated\.js"/);
  assert.ok(!browserEngine.includes('"./index.generated.mjs"'));
});

test("both index artifacts describe the same pages", async () => {
  const full = await import("../src/index.generated.mjs");
  const slim = await import("../public/index.generated.js");
  assert.equal(slim.DOCS.length, full.DOCS.length);
  assert.deepEqual(slim.INDEX_META.contentHash, full.INDEX_META.contentHash);
  assert.deepEqual(slim.INDEX_META.pageCount, full.INDEX_META.pageCount);
  const fullIds = full.DOCS.map((doc) => doc.id);
  const slimIds = slim.DOCS.map((doc) => doc.id);
  assert.deepEqual(slimIds, fullIds, "page ids differ between artifacts");
  for (let i = 0; i < full.DOCS.length; i += 1) {
    const a = full.DOCS[i];
    const b = slim.DOCS[i];
    assert.equal(b.title, a.title, `${a.id}: title differs`);
    assert.equal(b.url, a.url, `${a.id}: url differs`);
    assert.equal(b.plain, a.plain, `${a.id}: plain text differs`);
  }
});

test("the browser artifact stays slim", async () => {
  const slim = await import("../public/index.generated.js");
  for (const doc of slim.DOCS) {
    assert.equal(doc.text, undefined, `${doc.id}: markdown text should not ship to the browser`);
    assert.ok(doc.plain, `${doc.id}: plain text is required for search`);
  }
  const bytes = Buffer.byteLength(read("public", "index.generated.js"), "utf8");
  assert.ok(bytes < 700_000, `browser index is ${Math.round(bytes / 1024)}KB — too large`);
});

test("the dashboard loads its engine and index, and hardcodes no page content", () => {
  const html = read("public", "index.html");
  assert.match(html, /<script type="module" src="\/app\.js">/);
  assert.match(html, /href="\/style\.css"/);
  const app = read("public", "app.js");
  assert.match(app, /from "\.\/kb\.mjs"/);
  assert.ok(!/https:\/\/docs\.pharos\.xyz\/(getting-started|developer-guide|api-and-sdk)\//.test(app), "app.js must not hardcode page urls");
  assert.ok(!/TODO|FIXME|Lorem ipsum/i.test(app + html), "no placeholder text in shipped ui");
});

test("the landing page documents the api it actually serves", () => {
  const html = read("public", "index.html");
  for (const endpoint of ["/api/search", "/api/ask", "/api/doc", "/api/meta"]) {
    assert.ok(html.includes(endpoint), `landing page does not mention ${endpoint}`);
  }
});

test("package.json wires the scripts the README promises", () => {
  const pkg = JSON.parse(read("package.json"));
  for (const script of ["test", "build:index", "verify", "dev", "deploy"]) {
    assert.ok(pkg.scripts[script], `missing npm script: ${script}`);
  }
  assert.equal(pkg.bin["pharos-docs"], "./src/cli.mjs");
  assert.equal(pkg.type, "module");
  assert.ok(pkg.engines?.node, "engines.node should be declared");
});

test("404.html exists, reuses the stylesheet, and names the real routes", () => {
  const html = read("public", "404.html");
  assert.match(html, /href="\/style\.css"/);
  assert.match(html, /href="\/"/);
  for (const route of ["/api/search", "/api/ask", "/api/doc", "/api/meta"]) {
    assert.ok(html.includes(route), `404 page omits ${route}`);
  }
});

test("shipping metadata has no placeholders and points at a real repo", () => {
  const pkg = JSON.parse(read("package.json"));
  assert.match(pkg.repository.url, /github\.com\/arraya20\/pharos-doc-search/);
  assert.ok(!/USER|CHANGEME|example\.com/.test(pkg.repository.url + pkg.homepage));
  assert.equal(pkg.license, "MIT");
  assert.match(read("LICENSE"), /MIT License/);
  const skill = read("SKILL.md");
  assert.match(skill, /^---\nname: pharos-doc-search\n/, "SKILL.md needs frontmatter");
  assert.match(skill, /^version: \d+\.\d+\.\d+$/m);
});

test("the hidden attribute actually hides things", () => {
  const css = read("public", "style.css");
  // Component rules like `.field { display: flex }` outrank the UA `[hidden]`
  // rule, which left the goal input visible while in Search mode.
  assert.match(css, /\[hidden\]\s*\{\s*display:\s*none\s*!important;?\s*\}/);
  const html = read("public", "index.html");
  assert.match(html, /id="goal-row"[^>]*hidden/, "the goal row must start hidden");
});

test("_headers ships a CSP that the pages can actually satisfy", () => {
  const headers = read("public", "_headers");
  assert.match(headers, /Content-Security-Policy: [^\n]*script-src 'self'/);
  assert.match(headers, /frame-ancestors 'none'/);
  assert.match(headers, /\/api\/\*\n\s+Cache-Control: no-store/);
  // A strict CSP without 'unsafe-inline' only works while the HTML has no inline
  // script, style attribute or javascript: URL. Fail here, not in a browser.
  for (const page of ["index.html", "404.html"]) {
    const html = read("public", page);
    assert.doesNotMatch(html, /<script(?![^>]*\bsrc=)/i, `${page} has an inline script`);
    assert.doesNotMatch(html, /\sstyle=/i, `${page} has an inline style attribute`);
    assert.doesNotMatch(html, /javascript:/i, `${page} has a javascript: URL`);
  }
});

test("the browser copy of the search engine is not a stale hand copy", () => {
  // public/kb.mjs is src/kb.mjs with the import rewritten for the browser. If it
  // drifts, the page silently searches an old engine — which is exactly what a
  // hand `cp` produces.
  const src = read("src", "kb.mjs");
  const pub = read("public", "kb.mjs");
  const expected = src
    .replace('from "./index.generated.mjs"', 'from "./index.generated.js"')
    .replace(
      "// Search engine over the generated Pharos documentation index.",
      "// Copy of src/kb.mjs generated by scripts/build-index.mjs — do not edit.\n// Search engine over the generated Pharos documentation index."
    );
  assert.equal(pub, expected, "public/kb.mjs is out of sync — run npm run build:index");
});
